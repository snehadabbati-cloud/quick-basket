import 'package:flutter/material.dart';

/// Responsive wrapper ensuring standard mobile layout centers cleanly on desktop/web
/// with full bounded height for Expanded columns (PRD Section 2)
class ResponsiveWrapper extends StatelessWidget {
  final Widget child;
  final double maxWidth;

  const ResponsiveWrapper({
    super.key,
    required this.child,
    this.maxWidth = 1200,
  });

  @override
  Widget build(BuildContext context) {
    return Center(
      child: ConstrainedBox(
        constraints: BoxConstraints(maxWidth: maxWidth),
        child: child,
      ),
    );
  }
}
